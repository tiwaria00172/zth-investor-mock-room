import { Evaluation, StartupProfile } from '../types'

export function generateMarkdownReport(profile: StartupProfile, evaluation: Evaluation): string {
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  })

  let md = `# ZTH Investor Readiness Assessment\n\n`
  md += `**Startup:** ${profile.name || 'Startup'}\n`
  md += `**Industry:** ${profile.industry || 'Not specified'}\n`
  md += `**Fundraising Stage:** ${profile.stage || 'Not specified'}\n`
  md += `**Assessment Date:** ${date}\n`
  md += `**Overall Readiness Score:** ${evaluation.overall_score}/100\n\n`
  md += `---\n\n`
  md += `## Executive Summary\n\n`
  md += `${evaluation.startup_summary}\n\n`
  md += `> **Coach's Note:** ${evaluation.score_note}\n\n`

  md += `## Category Rubric Breakdown\n\n`
  md += `| Category | Score | Slide Evidence | Rationale |\n`
  md += `| :--- | :---: | :---: | :--- |\n`
  for (const cat of evaluation.categories) {
    const slides = cat.slide_numbers?.length ? `Slide ${cat.slide_numbers.join(', ')}` : 'N/A'
    md += `| **${cat.name}** | ${cat.score}/10 | ${slides} | ${cat.reason.replace(/\|/g, '-')} |\n`
  }
  md += `\n`

  if (evaluation.strengths?.length) {
    md += `## Key Strengths\n\n`
    for (const s of evaluation.strengths) {
      const slides = s.slide_numbers?.length ? ` *(Slide ${s.slide_numbers.join(', ')})*` : ''
      md += `- **${s.point}**${slides}\n`
    }
    md += `\n`
  }

  if (evaluation.improvements?.length) {
    md += `## Priority Improvements for Investors\n\n`
    for (const imp of evaluation.improvements) {
      const slides = imp.slide_numbers?.length ? ` [Slide ${imp.slide_numbers.join(', ')}]` : ''
      md += `### [${imp.priority.toUpperCase()} PRIORITY] ${imp.issue}${slides}\n\n`
      md += `**Why it matters:** ${imp.why_it_matters}\n\n`
      md += `**Recommendation:** ${imp.recommendation}\n\n`
    }
  }

  if (evaluation.missing_information?.length) {
    md += `## Information to Add or Verify\n\n`
    for (const item of evaluation.missing_information) {
      md += `- ${item}\n`
    }
    md += `\n`
  }

  md += `---\n`
  md += `*Report generated by ZTH Investor Mock Room. Automated coaching assessment based on deck text analysis.*\n`

  return md
}

export function downloadMarkdownFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.setAttribute('href', url)
  link.setAttribute('download', filename)
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}
